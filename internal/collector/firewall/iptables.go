package firewall

import (
	"bufio"
	"bytes"
	"strings"
)

// Ruleset is the output of iptables-save or ip6tables-save.
type Ruleset struct {
	// Backend is the kernel interface the iptables tools use: "nf_tables"
	// (iptables-nft, the default on recent distributions) or "legacy".
	Backend string  `json:"backend,omitempty"`
	Tables  []Table `json:"tables"`
}

// Table is an iptables table (filter, nat, mangle, raw, security).
type Table struct {
	Name   string  `json:"name"`
	Chains []Chain `json:"chains"`
}

// Chain is a chain and its rules, in order.
type Chain struct {
	Name string `json:"name"`

	// Policy is what happens to packets no rule decides (ACCEPT, DROP). Only
	// the built-in chains have one; empty for the user-defined chains.
	Policy string `json:"policy,omitempty"`

	// Rules are the rule specifications as iptables-save prints them, without
	// the "-A CHAIN" prefix: "-p tcp -m tcp --dport 22 -j ACCEPT".
	Rules []string `json:"rules"`
}

// HasChain reports whether a table holds a chain.
func (r *Ruleset) HasChain(table, chain string) bool {
	return r.Chain(table, chain) != nil
}

// Chain returns a chain of a table, or nil.
func (r *Ruleset) Chain(table, chain string) *Chain {
	if r == nil {
		return nil
	}
	for i := range r.Tables {
		if r.Tables[i].Name != table {
			continue
		}
		for j := range r.Tables[i].Chains {
			if r.Tables[i].Chains[j].Name == chain {
				return &r.Tables[i].Chains[j]
			}
		}
	}
	return nil
}

// parseIptablesSave parses the iptables-save format:
//
//	# Generated by iptables-save v1.8.10 (nf_tables) on ...
//	*filter
//	:INPUT DROP [0:0]
//	:DOCKER-USER - [0:0]
//	-A INPUT -i lo -j ACCEPT
//	COMMIT
func parseIptablesSave(data []byte) *Ruleset {
	rs := &Ruleset{Tables: []Table{}}
	var table *Table
	index := map[string]int{} // chain name -> position in table.Chains

	chain := func(name string) *Chain {
		i, ok := index[name]
		if !ok {
			// A rule may reference a chain before its declaration in hand
			// written files; iptables-save always declares first.
			table.Chains = append(table.Chains, Chain{Name: name, Rules: []string{}})
			i = len(table.Chains) - 1
			index[name] = i
		}
		return &table.Chains[i]
	}

	sc := bufio.NewScanner(bytes.NewReader(data))
	sc.Buffer(make([]byte, 0, 64*1024), 1024*1024) // rules with long comments or sets
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		switch {
		case line == "":
		case strings.HasPrefix(line, "#"):
			if rs.Backend == "" {
				rs.Backend = backendOf(line)
			}
		case strings.HasPrefix(line, "*"):
			rs.Tables = append(rs.Tables, Table{Name: line[1:], Chains: []Chain{}})
			table = &rs.Tables[len(rs.Tables)-1]
			index = map[string]int{}
		case table == nil:
			// Rules outside a table: not iptables-save output.
		case strings.HasPrefix(line, ":"):
			f := strings.Fields(line[1:])
			if len(f) == 0 {
				continue
			}
			ch := chain(f[0])
			if len(f) > 1 && f[1] != "-" {
				ch.Policy = f[1]
			}
		case strings.HasPrefix(line, "-A "):
			name, spec, _ := strings.Cut(strings.TrimPrefix(line, "-A "), " ")
			ch := chain(name)
			ch.Rules = append(ch.Rules, strings.TrimSpace(spec))
		case line == "COMMIT":
			table = nil
		}
	}
	return rs
}

// backendOf extracts the variant from the header comment of iptables-save:
// "# Generated by iptables-save v1.8.7 (nf_tables) on ...".
func backendOf(comment string) string {
	_, rest, ok := strings.Cut(comment, "(")
	if !ok {
		return ""
	}
	variant, _, ok := strings.Cut(rest, ")")
	if !ok {
		return ""
	}
	return variant
}
