func TestParseCapEff(t *testing.T) {
	tests := []struct {
		in    string
		mask  uint64
		found bool
	}{
		{"Name:\tprobe\nCapInh:\t0000000000000000\nCapEff:\t000001ffffffffff\n", 0x1ffffffffff, true},
		{"CapEff:\t0000000000000000\n", 0, true},
		{"CapEff:\tzz\n", 0, false},
		{"Name:\tprobe\n", 0, false},
	}
	for _, tt := range tests {
		mask, found := parseCapEff([]byte(tt.in))
		if mask != tt.mask || found != tt.found {
			t.Errorf("parseCapEff(%q) = %x, %v", tt.in, mask, found)
		}
	}
}
