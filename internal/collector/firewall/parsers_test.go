const iptablesSave = `# Generated by iptables-save v1.8.10 (nf_tables) on Mon Nov  2 10:00:00 2026
*nat
:PREROUTING ACCEPT [0:0]
:DOCKER - [0:0]
-A PREROUTING -m addrtype --dst-type LOCAL -j DOCKER
-A DOCKER -p tcp -m tcp --dport 8080 -j DNAT --to-destination 172.17.0.2:80
COMMIT
# Completed on Mon Nov  2 10:00:00 2026
*filter
:INPUT DROP [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
:DOCKER-USER - [0:0]
:ufw-user-input - [0:0]
-A INPUT -i lo -j ACCEPT
-A INPUT -p tcp -m tcp --dport 22 -m comment --comment "ssh access" -j ACCEPT
-A DOCKER-USER -j RETURN
COMMIT
`

func TestParseIptablesSave(t *testing.T) {
	rs := parseIptablesSave([]byte(iptablesSave))

	if rs.Backend != "nf_tables" {
		t.Errorf("Backend = %q", rs.Backend)
	}
	if len(rs.Tables) != 2 || rs.Tables[0].Name != "nat" || rs.Tables[1].Name != "filter" {
		t.Fatalf("tables = %+v", rs.Tables)
	}

	input := rs.Chain("filter", "INPUT")
	if input == nil || input.Policy != "DROP" {
		t.Fatalf("INPUT = %+v", input)
	}
	want := []string{"-i lo -j ACCEPT", `-p tcp -m tcp --dport 22 -m comment --comment "ssh access" -j ACCEPT`}
	if !reflect.DeepEqual(input.Rules, want) {
		t.Errorf("INPUT rules = %q", input.Rules)
	}

	du := rs.Chain("filter", "DOCKER-USER")
	if du == nil || du.Policy != "" || len(du.Rules) != 1 {
		t.Errorf("DOCKER-USER = %+v", du)
	}
	if !rs.HasChain("filter", "ufw-user-input") || rs.HasChain("nat", "ufw-user-input") {
		t.Error("HasChain does not distinguish tables")
	}
	if c := rs.Chain("filter", "ufw-user-input"); c.Rules == nil {
		t.Error("an empty chain must have an empty, non-nil rule list")
	}
}

func TestParseIptablesSave_LegacyAndEmpty(t *testing.T) {
	rs := parseIptablesSave([]byte("# Generated by iptables-save v1.8.7 (legacy) on x\n"))
	if rs.Backend != "legacy" || len(rs.Tables) != 0 || rs.Tables == nil {
		t.Errorf("got %+v", rs)
	}
	var nilRS *Ruleset
	if nilRS.HasChain("filter", "INPUT") {
		t.Error("a nil ruleset has no chain")
	}
}

const nftRuleset = `table inet filter {
	set allowed {
		type ipv4_addr
		elements = { 10.0.0.1,
			     10.0.0.2 }
	}

	chain input {
		type filter hook input priority filter; policy drop;
		comment "host input"
		ct state established,related accept
		iif "lo" accept
		tcp dport { 22, 443 } counter packets 12 bytes 3456 accept
	}

	chain forward {
		type filter hook forward priority filter - 10; policy accept;
	}

	chain helper {
		counter packets 0 bytes 0
	}
}
table ip nat {
	map ports { type inet_service : ipv4_addr; elements = { 80 : 10.0.0.1 } }
	chain prerouting {
		type nat hook prerouting priority dstnat; policy accept;
	}
}
`

func TestParseNftRuleset(t *testing.T) {
	got := parseNftRuleset([]byte(nftRuleset))

	want := &Nftables{Tables: []NftTable{
		{
			Family: "inet", Name: "filter", Sets: []string{"allowed"},
			Chains: []NftChain{
				{
					Name: "input", Type: "filter", Hook: "input", Priority: "filter", Policy: "drop",
					Rules: []string{"ct state established,related accept", `iif "lo" accept`, "tcp dport { 22, 443 } counter accept"},
				},
				{Name: "forward", Type: "filter", Hook: "forward", Priority: "filter - 10", Policy: "accept", Rules: []string{}},
				{Name: "helper", Rules: []string{"counter"}},
			},
		},
		{
			Family: "ip", Name: "nat", Sets: []string{"ports"},
			Chains: []NftChain{{Name: "prerouting", Type: "nat", Hook: "prerouting", Priority: "dstnat", Policy: "accept", Rules: []string{}}},
		},
	}}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("parseNftRuleset:\n got %+v\nwant %+v", got, want)
	}
}

func TestParseNftRuleset_Empty(t *testing.T) {
	got := parseNftRuleset(nil)
	if got.Tables == nil || len(got.Tables) != 0 {
		t.Errorf("got %+v", got)
	}
}

const ufwUserRules = `*filter
:ufw-user-input - [0:0]
### RULES ###

### tuple ### allow tcp 22 0.0.0.0/0 any 0.0.0.0/0 in
-A ufw-user-input -p tcp --dport 22 -j ACCEPT

### tuple ### allow tcp 80,443 0.0.0.0/0 any 0.0.0.0/0 Nginx%20Full - in
-A ufw-user-input -p tcp -m multiport --dports 80,443 -j ACCEPT

### tuple ### deny tcp 3306 0.0.0.0/0 any 192.168.1.0/24 in_eth0 comment=6e6f206462
-A ufw-user-input -i eth0 -p tcp --dport 3306 -s 192.168.1.0/24 -j DROP

### tuple ### limit_log tcp 2222 0.0.0.0/0 any 0.0.0.0/0 in
### tuple ### route:allow tcp 8080 0.0.0.0/0 any 0.0.0.0/0 in
### tuple ### broken line
### END RULES ###
COMMIT
`

func TestParseUFWRules(t *testing.T) {
	got := parseUFWRules([]byte(ufwUserRules), false)
	want := []UFWRule{
		{Action: "allow", Direction: "in", Protocol: "tcp", Port: "22", To: "0.0.0.0/0", From: "0.0.0.0/0", FromPort: "any"},
		{Action: "allow", Direction: "in", Protocol: "tcp", Port: "80,443", To: "0.0.0.0/0", From: "0.0.0.0/0", FromPort: "any", App: "Nginx Full"},
		{Action: "deny", Direction: "in", Interface: "eth0", Protocol: "tcp", Port: "3306", To: "0.0.0.0/0", From: "192.168.1.0/24", FromPort: "any", Comment: "no db"},
		{Action: "limit", Log: true, Direction: "in", Protocol: "tcp", Port: "2222", To: "0.0.0.0/0", From: "0.0.0.0/0", FromPort: "any"},
		{Action: "allow", Route: true, Direction: "in", Protocol: "tcp", Port: "8080", To: "0.0.0.0/0", From: "0.0.0.0/0", FromPort: "any"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("parseUFWRules:\n got %+v\nwant %+v", got, want)
	}

	if r := parseUFWRules([]byte(ufwUserRules), true); len(r) == 0 || !r[0].IPv6 {
		t.Error("rules of user6.rules must be marked IPv6")
	}
}

